const DICTS: Record<Locale, Dict> = { es: ES, en: EN };

// [fmt]: «{n} palabras» + {n: 3} → «3 palabras» | `replace` con callback (ES) | [Paradigma]: Funcional (pura)
export const fmt = (template: string, vars: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));

@Injectable({ providedIn: 'root' })
export class I18nService {
  // `signal(inject(LOCALE))`: idioma inicial de la cookie del shell; `use()` lo cambia en caliente (pruebas, futuros selectores)
  readonly locale = signal<Locale>(inject(LOCALE));
  // `computed` (Angular): diccionario activo → las plantillas leen `i18n.t().assistant.title` y se repintan al cambiar el idioma
  readonly t = computed(() => DICTS[this.locale()]);
  // [shell]: diccionario de Next.js en el mismo idioma → `i18n.shell().nav.tutor` es el mismo texto que pinta el sidebar de Next.js
  readonly shell = computed(() => getDictionary(this.locale()));
  // [intl]: etiqueta BCP 47 para `Intl` / `toLocaleString` (la misma que usa Next.js: es-CO / en-US)
  readonly intl = computed(() => INTL_LOCALE[this.locale()]);

  // [use]: cambia el idioma en caliente y lo guarda en la cookie `ui-lang` (un año) → Next.js renderiza en el mismo idioma al volver | `document.cookie` (DOM)
  use(locale: Locale): void {
    this.locale.set(locale);
    document.cookie = `${LOCALE_COOKIE}=${locale}; path=/; max-age=31536000; samesite=lax`;
  }

  readonly fmt = fmt;

  // [languageName]: «en» → «Inglés» en el idioma de la interfaz; código desconocido → el propio código | `as Record<string,string>` (TS): índice por string seguro
  languageName(code: string): string {
    return (this.shell().languageNames as Record<string, string>)[code.toUpperCase()] ?? code; // Claves del diccionario en mayúscula (EN, FR…)
  }
}
